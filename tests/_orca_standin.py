"""A stand-in OrcaSlicer 2.4.2 CLI for tests/test_fdm_slice.py.

It answers the two calls fdm.slice makes, in the shapes Orca 2.4.2 used while the
gate was written: ``--help`` prints the ``OrcaSlicer-<v>:`` banner; a slice
writes ``out/result.json`` (``return_code``, ``error_string``, ``sliced_plates[*]
.warning_message``) and, on return code 0, ``out/plate_1.gcode`` with the
``; generated by OrcaSlicer <v> on`` header, ``M83``, the test's own ``;TYPE:``
toolpaths and a CONFIG_BLOCK that echoes the presets it was handed, as Orca does
(lists joined by commas, newlines escaped, each preset's ``name`` as its
``*_settings_id``, the file keys not echoed); and it exits ``return_code`` mod
256. None of its text is Orca's: the words and the toolpaths are the test's.

What it does is set by ``mode.json`` beside it, which the test writes: ``version``
(the banner), ``header`` (the G-code's version), ``rc``, ``words``, ``warning``,
``exit``, ``sleep``, ``no_result``, ``absolute`` (``M82``), ``drop`` (keys left out
of the echo), ``set`` (keys echoed at another value), ``body`` (the toolpaths) and
``help_crash`` (``--help`` writes a loader error and exits 127).
Each call is logged to ``calls`` beside it.

Not a test module: its name starts with ``_``, as tests/_env.py's does.
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(HERE, "mode.json"), encoding="utf-8") as fh:
    MODE = json.load(fh)
with open(os.path.join(HERE, "calls"), "a", encoding="utf-8") as fh:
    fh.write(" ".join(sys.argv[1:]) + "\n")
VERSION = MODE.get("version", "2.4.2")

if "--help" in sys.argv:
    if MODE.get("help_crash"):
        # A slicer on PATH that cannot start: the loader's words, exit 127.
        sys.stderr.write("orca-slicer: error while loading shared libraries: stand-in.so\n")
        sys.exit(127)
    print(f"OrcaSlicer-{VERSION}:")
    print("Usage: orca-slicer [ OPTIONS ] [ file.3mf/file.stl ... ]")
    sys.exit(0)

args = sys.argv[1:]


def opt(name):
    return args[args.index(name) + 1]


machine, process = opt("--load-settings").split(";")
roles = {"machine": machine, "process": process, "filament": opt("--load-filaments")}
out = opt("--outputdir")
time.sleep(MODE.get("sleep", 0))
os.makedirs(out, exist_ok=True)
rc = int(MODE.get("rc", 0))

#: What the real CLI leaves out of the echo (the gate's PRESET_META_KEYS, as
#: measured; restated here, never imported).
FILE_KEYS = {"type", "name", "from", "instantiation", "setting_id", "filament_id",
             "compatible_printers"}
IDS = {"machine": "printer_settings_id", "process": "print_settings_id",
       "filament": "filament_settings_id"}
echo = {"layer_height": "0.2", "initial_layer_print_height": "0.2",
        "support_top_z_distance": "0.2", "enable_arc_fitting": "0"}
for role, path in roles.items():
    with open(path, encoding="utf-8") as fh:
        preset = json.load(fh)
    for key, value in preset.items():
        if key in FILE_KEYS:
            continue
        echo[key] = (",".join(str(v) for v in value) if isinstance(value, list)
                     else str(value).replace("\n", "\\n"))
    echo[IDS[role]] = f'"{preset["name"]}"' if role == "filament" else preset["name"]
for key in MODE.get("drop", ()):
    echo.pop(key, None)
echo.update(MODE.get("set", {}))

if not MODE.get("no_result"):
    with open(os.path.join(out, "result.json"), "w", encoding="utf-8") as fh:
        json.dump({"return_code": rc, "error_string": MODE.get("words", "Success."),
                   "sliced_plates": [{"id": 1, "warning_message": MODE.get("warning", "")}]},
                  fh, indent=1)
if rc == 0:
    lines = ["; HEADER_BLOCK_START",
             f"; generated by OrcaSlicer {MODE.get('header', VERSION)} on 2026-10-30 at 00:00:00",
             "; HEADER_BLOCK_END", ";TYPE:Custom", "G28", "G90",
             "M82" if MODE.get("absolute") else "M83", MODE.get("body", ""),
             "; CONFIG_BLOCK_START", *(f"; {k} = {v}" for k, v in sorted(echo.items())),
             "; CONFIG_BLOCK_END"]
    with open(os.path.join(out, "plate_1.gcode"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
sys.exit(int(MODE.get("exit", rc % 256)))
