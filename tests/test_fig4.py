def _flat(root: str) -> dict:
    from nopekit import cli, modelio, store
    ledger = store.load(root)
    _model, projection, _error = cli._projection_safe(root, ledger)
    return modelio.flat_params(projection)[0]


def package_problems(carried: Mapping[str, Any], root: str, name: str) -> list[str]:
    """Every value a package's `model.json` carries that its export's article
    does not record (``built_from``'s params, by dotted path)."""
    article = P.exports(root, name)["exports"][-1]["article"]
    rows = {".".join(str(p) for p in row[0]) for row in article["built_from"]["params"]}
    return [key for key in carried if key not in rows]


